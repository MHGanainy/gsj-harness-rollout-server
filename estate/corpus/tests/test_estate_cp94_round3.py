def partial_record(corpus: str) -> dict:
    return {"schema": 1, "run": "canary", "run_dir": "/disposable/canary",
            "corpus": {"path": corpus, "name": "my-corpus", "owner": "my-owner",
                       "case_ids": ["case_0001"]},
            "forgejo": {"mode": "created", "url": "http://127.0.0.1:9",
                        "container_url": "http://gsj-canary-forgejo:3000",
                        "admin_user": "gsj-admin", "admin_credential_env": "X",
                        "require_signin_view": True},
            "compose": {"mcp": {"image": "registry.invalid/gsj-mcp-service:9",
                                "container": "gsj-canary-mcp", "port": 8790,
                                "data": "/d", "config": "/c", "read_env": "R"}},
            "secrets": {"names": []}}


def partial_run(runs: Path, *, compose_yaml: bool = False) -> Path:
    rd = runs / "canary"
    rd.mkdir(parents=True)
    corpus = runs / "corpus"
    corpus.mkdir()
    (rd / "run.json").write_text(json.dumps(partial_record(str(corpus))))
    (rd / ".env").write_text("")
    if compose_yaml:
        (rd / "compose.yaml").write_text("# GENERATED by estate.py for run canary\n")
    return rd


# ------------------------------------------------ status: three states, not two

def hold_lock(runs: Path, name: str):
    """What `up` does for its whole command: an exclusive kernel lock on
    <runs>/.locks/<name>.lock (a separate open file description, so the
    subprocess's non-blocking probe sees it held)."""
    locks = runs / ".locks"
    locks.mkdir(exist_ok=True, mode=0o700)
    handle = open(locks / f"{name}.lock", "w")
    fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
    return handle


def test_status_says_active_and_wait_while_up_holds_the_lock(tmp_path):
    """Two strangers ran `status` mid-`up` and were told the run had died
    (b1) or that nothing was running (a1, the demo): a held lock is a run
    in flight — say so, say wait, recommend nothing."""
    partial_run(tmp_path)
    handle = hold_lock(tmp_path, "canary")
    try:
        proc = invoke(tmp_path, "status", "--name", "canary")
    finally:
        fcntl.flock(handle, fcntl.LOCK_UN)
        handle.close()
    assert proc.returncode == 0, proc.stderr
    out = proc.stdout
    assert "== run canary ==" in out and "ACTIVE" in out and "still running" in out
    assert "is ACTIVE — wait for the running command" in out
    assert "Do not start a second `up`" in out and "never delete the lock file" in out
    # the phases that stand are still reported — the same rows as the incomplete report
    assert "corpus    my-corpus: 1 case(s); owner 'my-owner'" in out
    # an active run has not died: what it has not reached, it has not reached YET
    assert "mcp       not reached yet — up is in or before this phase" in out
    assert "taskbank  not reached yet" in out and "engine    not recorded yet" in out
    assert "config    not written yet" in out and "died" not in out
    # and none of the incomplete report's verdicts: no refusal, no resume cure
    assert "REFUSED" not in proc.stderr and "incomplete" not in out
    assert "to resume" not in out and "to resume" not in proc.stderr
    assert "Traceback" not in proc.stderr


