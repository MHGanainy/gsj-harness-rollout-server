def test_up_refuses_an_absent_sandbox_image_before_any_container_is_pulled_or_created(tmp_path):
    """A stranger's `up` ran 41 minutes of pipeline — Forgejo, owner, tokens,
    repos, a 1.28 GiB pull, an index — and then met this refusal for an
    image whose name it had printed at +0.0s. The check sits with the
    preflight now: the only Docker calls before the refusal are the daemon
    probe and the image inspection, and the refusal text is CP-92's."""
    if not STAGING.is_dir():
        pytest.skip("the checkout's staging corpus is the default --corpus")
    docker = fake_docker(tmp_path / ".fake",
                         'case "$1 $2" in\n'
                         '  "info --format") echo 29.0.0; exit 0 ;;\n'
                         '  "image inspect") echo "No such image" >&2; exit 1 ;;\n'
                         'esac\necho "unexpected docker call: $*" >&2; exit 97\n')
    proc = invoke(tmp_path, "up", "-y", "--name", "canary", "--corpus", str(STAGING),
                  docker=docker)
