class FakeEngine:
    """A vLLM-shaped OpenAI endpoint on a loopback port: /v1/models, the
    messages form of /tokenize, and /v1/chat/completions either served WITH
    the tool flags (200 + logprobs) or WITHOUT (vLLM's 400 body)."""

    def __init__(self, *, tool_flags: bool):
        import http.server
        import threading
        marker = [151645]
        base = [151644, 872, 198, 9707, 13, 151645, 198]              # <|im_start|>user\nHello.<|im_end|>\n
        tail = [151644, 77091, 198, 151667, 271, 151668, 271]         # the generation prompt

        class Handler(http.server.BaseHTTPRequestHandler):
            def log_message(self, *a):  # quiet
                pass

            def _send(self, code, body):
                data = json.dumps(body).encode()
                self.send_response(code)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)

            def do_GET(self):
                assert self.path == "/v1/models"
                self._send(200, {"data": [{"id": "fake-model", "max_model_len": 4096}]})

            def do_POST(self):
                payload = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
                if self.path == "/tokenize":
                    if "prompt" in payload:
                        return self._send(200, {"tokens": marker})
                    msgs = payload["messages"]
                    ids = list(base) + (list(base) if len(msgs) > 1 else [])
                    if payload.get("add_generation_prompt"):
                        ids += tail
                    return self._send(200, {"tokens": ids})
                assert self.path == "/v1/chat/completions"
                if payload.get("tool_choice") == "auto" and not tool_flags:
                    return self._send(400, json.loads(VLLM_400))
                return self._send(200, {"choices": [{"finish_reason": "stop",
                                                     "message": {"role": "assistant", "content": "OK."},
                                                     "logprobs": {"content": [{"token": "OK", "logprob": -0.01}]}}]})

        self.server = http.server.HTTPServer(("127.0.0.1", 0), Handler)
        self.url = f"http://127.0.0.1:{self.server.server_port}"
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    def close(self):
        self.server.shutdown()


